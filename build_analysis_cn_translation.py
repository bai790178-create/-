from pathlib import Path

import build_ai_communication_report_cn as cn
from docx import Document


OUT = Path("report_output")


def build_doc():
    charts = cn.make_charts()
    doc = Document()
    cn.style_doc(doc)

    doc.add_heading("5. 发现与数据分析", level=1)
    doc.add_heading("5.1 年轻且高频使用者构成主要样本", level=2)
    cn.add_para(doc, "样本明显集中在年轻用户群体中。第 1 题显示，72% 的受访者年龄在 18 至 35 岁之间。第 2 题显示，65.33% 的受访者每天使用 AI，其余受访者也至少每两三天使用一次，没有人选择“几乎不使用”。这一点很重要，因为本研究关注的是潜移默化的影响，而这种影响更可能出现在反复使用 AI 的人身上。")
    cn.add_figure_pair(doc, (charts["q1"], "图1 第1题年龄分布。"), (charts["q2"], "图2 第2题 AI 使用频率。"))
    cn.add_para(doc, "由于大多数受访者都是 AI 的经常使用者，他们的回答更适合用来观察习惯，而不只是一次性的印象。虽然这些数据并不能均衡代表所有年龄群体，但它们正好对应了最可能在日常交流中受到 AI 影响的群体。")

    doc.add_heading("5.2 AI 的用途已经不只是获取信息", level=2)
    cn.add_para(doc, "第 3 题显示，AI 的使用正在从工具性用途转向情绪性用途。最多的受访者（88%）将 AI 作为搜索引擎使用，这一结果并不意外。更值得注意的是，42.67% 的受访者也会把 AI 当作倾诉对象，26.67% 会用 AI 咨询社交问题。这些数字说明，AI 正在进入一些过去更依赖朋友、同学或家人的交流空间。")
    cn.add_figure(doc, charts["q3"], "图3 第3题 AI 使用目的。")
    cn.add_para(doc, "这一点对本研究有帮助，因为它说明了影响可能发生在哪里。如果 AI 只是计算器或词典，它对交流方式的影响可能有限。但当它成为情绪表达和社交建议的对象时，它就开始塑造用户对“倾听者”的期待。")

    doc.add_heading("5.3 用户知道 AI 可能在奉承，但这种感觉仍然有效", level=2)
    cn.add_para(doc, "数据中最明显的模式，是用户的理性判断和情绪感受之间存在差距。第 4 题中，60% 的受访者认为 AI 的肯定完全或基本属于奉承。然而，第 5 题显示，76% 的受访者在被 AI 肯定时仍然会感到愉悦。第 6 题进一步补充说明：多数受访者并不是盲目服从 AI，因为最大比例的群体将自己采纳 AI 建议的概率放在 40-60 区间。")
    cn.add_figure_pair(doc, (charts["q4"], "图4 第4题 对 AI 肯定性质的判断。"), (charts["q5"], "图5 第5题 被 AI 肯定后的情绪反应。"))
    cn.add_figure(doc, charts["q6"], "图6 第6题 采纳 AI 建议的概率。")
    cn.add_para(doc, "这正是 AI 影响具有隐蔽性的原因。用户可能仍然保持理性，知道自己需要怀疑 AI，但情绪奖励依然会发挥作用。AI 提供了一种几乎没有尴尬和分歧风险的肯定。Linda 的访谈也支持这一点：她知道 AI 并不等同于真人，但她仍然喜欢那种被接纳的感觉。")

    doc.add_heading("5.4 便利性推动求助行为转向 AI", level=2)
    cn.add_para(doc, "第 7 题说明，高频使用 AI 并不主要来自盲目信任。受访者选择最多的两个原因是“AI 功能更丰富”和“与 AI 交流比询问他人更方便”，二者比例均为 68%。相比之下，选择“AI 信息可信度高”的比例只有 38.67%。也就是说，人们大量使用 AI，更多是因为它容易获得，而不是因为他们认为 AI 永远正确。")
    cn.add_figure(doc, charts["q7"], "图7 第7题 高强度使用 AI 的原因。")
    cn.add_para(doc, "这对交流研究很重要。向 AI 提问几乎没有社交成本。用户不需要担心打扰别人、被评价，或者收到负面回应。久而久之，这种低摩擦的习惯可能会让真实人际交流显得不那么有吸引力。")

    doc.add_heading("5.5 人际交流变得更加直接", level=2)
    cn.add_para(doc, "最后一组问题将 AI 使用与现实交流风格联系起来。第 9 题显示，73.33% 的受访者在向他人求助时仍然倾向于先说明原因，因此礼貌规范并没有消失。然而，第 10 题显示，53.33% 的受访者有时会省略语气词、铺垫和客套话；第 11 题显示，58.67% 的受访者认为自己最近的交流变得更直接，甚至更生硬。")
    cn.add_figure_pair(doc, (charts["q9"], "图8 第9题 向他人求助时的表达方式。"), (charts["q10"], "图9 第10题 是否省略语气词和客套话。"))
    cn.add_figure(doc, charts["q11"], "图10 第11题 表达是否更直接。")
    cn.add_para(doc, "这并不意味着 AI 已经消除了社交礼貌。真实情况更复杂：人们仍然知道人际交流应该如何进行，但一些 AI 式习惯可能正在进入日常表达，例如更短的措辞、更少的缓和语，以及更强的任务导向。")

    doc.add_heading("6. 访谈分析", level=1)
    cn.add_para(doc, "访谈让这些数字更容易理解。Linda 的案例展示了影响中的情绪一面。她一开始并没有说自己被 AI 改变了。只有在讨论具体情境之后，她才提到 AI 的肯定让她感到舒服，而来自真人的分歧更难面对。她的回答与问卷结果相吻合：许多用户即使知道 AI 可能在奉承，仍然会享受 AI 的肯定。")
    cn.add_para(doc, "Bob 的案例展示了另一种迁移。他对 AI 保持批判态度是合理的，因为 AI 可能出错。问题在于，这种习惯并不总是停留在 AI 使用场景中。在与同学交流时，他有时会比自己预期的更怀疑、更爱追问。这支持了我们的判断：围绕 AI 形成的习惯可能会泄露到人与人的互动中。")

    doc.add_heading("7. 讨论：数据反映了什么", level=1)
    cn.add_para(doc, "这些数据反映出三个主要现象。第一，AI 正在同时成为信息工具和情绪支持对象。第二，用户能够识别 AI 的奉承倾向，但仍会对这种肯定产生积极反应。第三，AI 互动中的直接性可能会影响人际交流的语气。")
    cn.add_para(doc, "这些发现把文献综述和我们的数据连接起来。文献解释了 AI 为什么可能产生幻觉或奉承用户；而我们的问卷和访谈进一步说明，这些模型特征可能对用户意味着什么：更依赖低摩擦的肯定，更容易回避令人不舒服的分歧，以及逐渐转向简洁但情绪缓冲较少的表达。")

    doc.add_heading("8. 结论", level=1)
    cn.add_para(doc, "本研究支持这一假设：AI 能够潜移默化地影响交流。这种影响并不夸张，也不一定立刻可见。它体现在许多反复出现的小体验中：即时得到回答、被礼貌地肯定、避免向真人求助时的尴尬，以及逐渐习惯直接、任务导向的语言。")
    cn.add_para(doc, "本项目也说明了间接研究方法的重要性。如果直接问人们 AI 是否改变了他们，许多人可能会回答没有。但当问题聚焦于具体习惯和具体情境时，模式就变得更清楚。未来研究可以比较高频和低频 AI 用户，扩大样本，并进一步观察真实交流记录随时间的变化。")

    out = OUT / "分析_中文版.docx"
    doc.save(out)
    return out


if __name__ == "__main__":
    print(build_doc())
